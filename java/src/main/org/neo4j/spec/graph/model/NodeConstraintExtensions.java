package org.neo4j.spec.graph.model;

import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Objects;

/** Extensions for a node constraint. */
public final class NodeConstraintExtensions {
    private final Map<String, Object> custom;

    private NodeConstraintExtensions(Builder b) {
        this.custom = Values.deepUnmodifiable(b.custom);
    }

    /**
     * Creates an empty builder.
     *
     * @return a new builder
     */
    public static Builder builder() {
        return new Builder();
    }

    /**
     * Creates a builder initialised with the values of this instance.
     *
     * @return a new builder
     */
    public Builder toBuilder() {
        return new Builder(this);
    }

    /** @return user-defined arbitrary data. */
    public Map<String, Object> custom() {
        return custom;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) {
            return true;
        }
        if (o == null || getClass() != o.getClass()) {
            return false;
        }
        NodeConstraintExtensions that = (NodeConstraintExtensions) o;
        return Objects.equals(custom, that.custom);
    }

    @Override
    public int hashCode() {
        return Objects.hash(custom);
    }

    @Override
    public String toString() {
        return "NodeConstraintExtensions{" + "custom=" + custom + "}";
    }

    /** Builder for {@link NodeConstraintExtensions}. */
    public static final class Builder {
        private final Map<String, Object> custom = new LinkedHashMap<>();

        private Builder() {}

        private Builder(NodeConstraintExtensions v) {
            this.custom.putAll(v.custom);
        }

        /**
         * Replaces user-defined arbitrary data.
         *
         * @param custom the entries, or null to clear
         * @return this builder
         */
        public Builder custom(Map<String, Object> custom) {
            this.custom.clear();
            if (custom != null) {
                this.custom.putAll(custom);
            }
            return this;
        }

        /**
         * Adds or replaces one entry.
         *
         * @param key the entry key
         * @param value the entry value
         * @return this builder
         */
        public Builder custom(String key, Object value) {
            this.custom.put(Objects.requireNonNull(key, "key"), value);
            return this;
        }

        /**
         * Builds the instance.
         *
         * @return the immutable instance
         * @throws IllegalStateException if a required field is missing
         */
        public NodeConstraintExtensions build() {
            return new NodeConstraintExtensions(this);
        }
    }
}

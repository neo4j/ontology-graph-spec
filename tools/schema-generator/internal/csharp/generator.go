// Package csharp emits C# models using the same schema model as the Go emitter.
package csharp

import (
	"bytes"
	"encoding/json"
	"fmt"
	"html"
	"strings"
	"unicode"

	"github.com/neo4j/ontology-graph-spec/tools/schema-generator/internal/model"
)

type Options struct {
	Namespace  string
	SchemaName string
	SchemaID   string
}

func Generate(m *model.Model, opts Options) ([]byte, error) {
	if err := checkNames(m, opts.Namespace); err != nil {
		return nil, err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// <auto-generated> From %s. Do not edit. </auto-generated>\n", opts.SchemaName)
	b.WriteString("// Copyright Neo4j Sweden AB. Licensed under the Apache License, Version 2.0.\n")
	b.WriteString("#nullable enable\n\nusing System;\nusing System.Collections.Generic;\nusing System.Text.Json;\nusing System.Text.Json.Serialization;\n\n")
	fmt.Fprintf(&b, "namespace %s;\n\n", opts.Namespace)
	if opts.SchemaID != "" {
		fmt.Fprintf(&b, "/// <summary>The specification described by the generation input.</summary>\npublic static class GraphSpecSchema\n{\n    public const string Url = %s;\n}\n\n", quote(opts.SchemaID))
	}
	for _, n := range m.NamedTypes {
		doc(&b, "", n.Doc)
		name := typeName(n)
		switch n.Kind {
		case model.Enum:
			fmt.Fprintf(&b, "[JsonConverter(typeof(SchemaStringEnumConverter<%s>))]\npublic enum %s\n{\n", name, name)
			for _, value := range n.Values {
				fmt.Fprintf(&b, "    [JsonStringEnumMemberName(%s)]\n    %s,\n", quote(value), identifier(value))
			}
			b.WriteString("}\n\n")
		case model.Union:
			fmt.Fprintf(&b, "[JsonConverter(typeof(%sJsonConverter))]\npublic interface %s { }\n\n", name, name)
		case model.Struct:
			fmt.Fprintf(&b, "public sealed class %s", name)
			var bases []string
			for _, tag := range n.Tags {
				bases = append(bases, typeName(tag.Union))
			}
			if len(bases) > 0 {
				fmt.Fprintf(&b, " : %s", strings.Join(bases, ", "))
			}
			b.WriteString("\n{\n")
			seenTags := map[string]bool{}
			for _, tag := range n.Tags {
				if seenTags[tag.Property] {
					continue
				}
				seenTags[tag.Property] = true
				fmt.Fprintf(&b, "    [JsonPropertyName(%s)]\n    public string %s => %s;\n\n", quote(tag.Property), identifier(tag.Property), quote(tag.Value))
			}
			for i, f := range n.Fields {
				doc(&b, "    ", f.Doc)
				fmt.Fprintf(&b, "    [JsonPropertyName(%s)]\n", quote(f.JSONName))
				required := ""
				if f.Required {
					required = "required "
				} else {
					b.WriteString("    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]\n")
				}
				fmt.Fprintf(&b, "    public %s%s %s { get; set; }\n", required, fieldType(f), identifier(f.JSONName))
				if i < len(n.Fields)-1 {
					b.WriteByte('\n')
				}
			}
			b.WriteString("}\n\n")
		}
	}
	b.WriteString("internal sealed class SchemaStringEnumConverter<T> : JsonStringEnumConverter<T> where T : struct, Enum\n{\n    public SchemaStringEnumConverter() : base(namingPolicy: null, allowIntegerValues: false) { }\n}\n")
	for _, n := range m.NamedTypes {
		if n.Kind != model.Union {
			continue
		}
		name := typeName(n)
		fmt.Fprintf(&b, "\ninternal sealed class %sJsonConverter : JsonConverter<%s>\n{\n", name, name)
		fmt.Fprintf(&b, "    public override %s Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)\n    {\n        using var document = JsonDocument.ParseValue(ref reader);\n        var root = document.RootElement;\n", name)
		fmt.Fprintf(&b, "        if (root.ValueKind != JsonValueKind.Object || !root.TryGetProperty(%s, out var tag) || tag.ValueKind != JsonValueKind.String)\n            throw new JsonException(%s);\n", quote(n.Discriminator), quote("Missing string discriminator "+n.Discriminator+" for "+name))
		b.WriteString("        return tag.GetString() switch\n        {\n")
		for _, v := range n.Variants {
			fmt.Fprintf(&b, "            %s => root.Deserialize<%s>(options)!,\n", quote(v.Value), typeName(v.Named))
		}
		fmt.Fprintf(&b, "            _ => throw new JsonException(%s)\n        };\n    }\n\n", quote("Unknown discriminator for "+name))
		fmt.Fprintf(&b, "    public override void Write(Utf8JsonWriter writer, %s value, JsonSerializerOptions options)\n    {\n        switch (value)\n        {\n", name)
		for _, v := range n.Variants {
			fmt.Fprintf(&b, "            case %s variant:\n                JsonSerializer.Serialize(writer, variant, options);\n                break;\n", typeName(v.Named))
		}
		fmt.Fprintf(&b, "            default:\n                throw new JsonException(%s);\n        }\n    }\n}\n", quote("Unsupported implementation of "+name))
	}
	return b.Bytes(), nil
}

func fieldType(f *model.Field) string {
	t := typeOf(f.Type)
	if !f.Required && !strings.HasSuffix(t, "?") {
		t += "?"
	}
	return t
}

func typeOf(t *model.Type) string {
	var name string
	switch t.Kind {
	case model.String:
		name = "string"
	case model.Integer:
		name = "long"
	case model.Number:
		name = "double"
	case model.Boolean:
		name = "bool"
	case model.Any:
		name = "JsonElement"
	case model.Ref:
		name = typeName(t.Named)
	case model.Array:
		name = "List<" + typeOf(t.Elem) + ">"
	case model.Map:
		name = "Dictionary<string, " + typeOf(t.Elem) + ">"
	}
	if t.Nullable {
		name += "?"
	}
	return name
}

func typeName(n *model.NamedType) string {
	name := identifier(n.Name)
	if u := n.VariantOf; u != nil {
		union := typeName(u)
		if !strings.HasPrefix(name, union) && !strings.HasSuffix(name, union) {
			name += union
		}
	}
	return name
}

func quote(s string) string {
	data, _ := json.Marshal(s)
	return string(data)
}

func doc(b *bytes.Buffer, indent, text string) {
	if text == "" {
		return
	}
	fmt.Fprintf(b, "%s/// <summary>\n", indent)
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimRight(line, " \t")
		if line == "" {
			fmt.Fprintf(b, "%s///\n", indent)
		} else {
			fmt.Fprintf(b, "%s/// %s\n", indent, html.EscapeString(line))
		}
	}
	fmt.Fprintf(b, "%s/// </summary>\n", indent)
}

func identifier(s string) string {
	runes := []rune(s)
	var words []string
	start := -1
	flush := func(end int) {
		if start >= 0 {
			words = append(words, string(runes[start:end]))
			start = -1
		}
	}
	for i, r := range runes {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			flush(i)
			continue
		}
		if start >= 0 && unicode.IsUpper(r) && (unicode.IsLower(runes[i-1]) || unicode.IsDigit(runes[i-1]) ||
			(unicode.IsUpper(runes[i-1]) && i+1 < len(runes) && unicode.IsLower(runes[i+1]))) {
			flush(i)
		}
		if start < 0 {
			start = i
		}
	}
	flush(len(runes))
	var b strings.Builder
	for _, word := range words {
		w := []rune(strings.ToLower(word))
		w[0] = unicode.ToUpper(w[0])
		b.WriteString(string(w))
	}
	name := b.String()
	if name != "" && unicode.IsDigit([]rune(name)[0]) {
		name = "Value" + name
	}
	return name
}

const keywords = " abstract as base bool break byte case catch char checked class const continue decimal default delegate do double else enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal is lock long namespace new null object operator out override params private protected public readonly ref return sbyte sealed short sizeof stackalloc static string struct switch this throw true try typeof uint ulong unchecked unsafe ushort using virtual void volatile while "

func checkNames(m *model.Model, namespace string) error {
	for _, part := range strings.Split(namespace, ".") {
		if part == "" || strings.Contains(keywords, " "+part+" ") {
			return fmt.Errorf("invalid C# namespace %q", namespace)
		}
		for i, r := range part {
			if r != '_' && !unicode.IsLetter(r) && !(i > 0 && unicode.IsDigit(r)) {
				return fmt.Errorf("invalid C# namespace %q", namespace)
			}
		}
	}
	types := map[string]string{"GraphSpecSchema": "schema metadata", "SchemaStringEnumConverter": "enum converter"}
	for _, name := range strings.Fields("Type Enum List Dictionary JsonElement JsonConverter JsonConverterAttribute JsonDocument JsonException JsonIgnore JsonIgnoreAttribute JsonIgnoreCondition JsonPropertyName JsonPropertyNameAttribute JsonSerializer JsonSerializerOptions JsonStringEnumConverter JsonStringEnumMemberName JsonStringEnumMemberNameAttribute JsonValueKind Utf8JsonReader Utf8JsonWriter") {
		types[name] = "C# runtime helper"
	}
	claim := func(names map[string]string, name, owner string) error {
		if name == "" {
			return fmt.Errorf("%s: cannot derive a C# identifier", owner)
		}
		if prev, ok := names[name]; ok {
			return fmt.Errorf("%s and %s both map to C# name %s", prev, owner, name)
		}
		names[name] = owner
		return nil
	}
	for _, n := range m.NamedTypes {
		name := typeName(n)
		if err := claim(types, name, n.Path); err != nil {
			return err
		}
		if n.Kind == model.Union {
			if err := claim(types, name+"JsonConverter", n.Path+" converter"); err != nil {
				return err
			}
		}
		members := map[string]string{name: n.Path + " enclosing type"}
		tags := map[string]string{}
		for _, tag := range n.Tags {
			if prior, ok := tags[tag.Property]; ok {
				if prior != tag.Value {
					return fmt.Errorf("%s: conflicting discriminator values for %s", n.Path, tag.Property)
				}
				continue
			}
			tags[tag.Property] = tag.Value
			if err := claim(members, identifier(tag.Property), n.Path+" discriminator"); err != nil {
				return err
			}
		}
		for _, f := range n.Fields {
			if err := claim(members, identifier(f.JSONName), f.Path); err != nil {
				return err
			}
		}
		for _, value := range n.Values {
			if err := claim(members, identifier(value), n.Path+" enum "+value); err != nil {
				return err
			}
		}
	}
	return nil
}
